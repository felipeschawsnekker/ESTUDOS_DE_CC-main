    private void SalvarBottonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SalvarBottonActionPerformed
           try {

        // Verifica se os campos estão vazios
        if (PacienteName.getText().trim().isEmpty()
                || PacienteAge.getText().trim().isEmpty()
                || PacienteCPF.getText().trim().isEmpty()
                || (!SimConvenioBotton.isSelected() && !NaoConvenioBotton.isSelected())) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Preencha todos os campos."
            );

            return;
        }

        // Caixa de confirmação
        Object[] opcoes = {"Sim", "Não"};

        int resposta = javax.swing.JOptionPane.showOptionDialog(
                this,
                "Tem certeza que deseja salvar?",
                "Confirmação",
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.QUESTION_MESSAGE,
                null,
                opcoes,
                opcoes[0]
        );

        // Se clicar em SIM
        if (resposta == javax.swing.JOptionPane.YES_OPTION) {

            // Captura os dados
            String nome = PacienteName.getText();

            int idade = Integer.parseInt(PacienteAge.getText());

            String cpf = PacienteCPF.getText();

            String convenio =
                    SimConvenioBotton.isSelected() ? "Sim" : "Não";

            // Controller
            PacienteController controller = new PacienteController();

            // Cadastro (pode lançar exceção)
            controller.cadastrarPaciente(nome, idade, cpf, convenio);

            // Mensagem de sucesso
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Cadastro realizado com sucesso!"
            );

            // Tabela
            DefaultTableModel tabela =
                    (DefaultTableModel) jTable1.getModel();

            tabela.addRow(new Object[]{nome, idade, cpf, convenio});

            // Limpa campos
            PacienteName.setText("");
            PacienteAge.setText("");
            PacienteCPF.setText("");
            buttonGroup1.clearSelection();

            // foco no nome
            PacienteName.requestFocus();
        }

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Digite apenas números na idade."
        );

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                e.getMessage()
        );
    }
         
    }//GEN-LAST:event_SalvarBottonActionPerformed

    private void RemoverBottonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_RemoverBottonActionPerformed

    int linha = jTable1.getSelectedRow();

    if (linha == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Selecione um paciente");
        return;
    }

    Object[] opcoes = {"Sim", "Não"};

    int resposta = javax.swing.JOptionPane.showOptionDialog(
            this,
            "Deseja remover?",
            "Confirmação",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.WARNING_MESSAGE,
            null,
            opcoes,
            opcoes[0]
    );

    if (resposta == javax.swing.JOptionPane.YES_OPTION) {

        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();

        model.removeRow(linha);

        // remove da lista também (IMPORTANTE)
        PacienteController.getListaPacientes().remove(linha);
    }
    }//GEN-LAST:event_RemoverBottonActionPerformed

