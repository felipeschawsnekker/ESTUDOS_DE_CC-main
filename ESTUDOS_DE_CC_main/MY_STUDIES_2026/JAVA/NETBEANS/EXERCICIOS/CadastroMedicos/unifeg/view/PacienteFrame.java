    private void carregarTabela() {

    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();

    model.setRowCount(0);

    for (Paciente p : PacienteController.getListaPacientes()) {
        model.addRow(new Object[]{
                p.getNome(),
                p.getIdade(),
                p.getCpf(),
                p.getConvenio()
        });
    }
}
